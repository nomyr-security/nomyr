package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"sort"
	"strings"
)

var publicInputs = []string{
	"api/openapi/v1.yaml",
	"cmd/nomyr/main.go",
	"cmd/nomyr/README.md",
	"internal/apperror/error.go",
	"requirements/catalog.json",
	"schemas/capability-manifest.schema.json",
	"schemas/event-envelope.schema.json",
}

var outputFiles = []string{
	"docs-site/docs/reference/cli.md",
	"docs-site/docs/reference/api.md",
	"docs-site/docs/reference/errors.md",
	"docs-site/docs/reference/configuration.md",
	"docs-site/docs/reference/contracts.md",
	"docs-site/docs/reference/capabilities.md",
	"docs-site/docs/reference/rules.md",
	"docs-site/docs/reference/events.md",
	"docs-site/docs/reference/requirements.md",
}

func main() {
	check := flag.Bool("check", false, "fail when generated documentation is stale")
	flag.Parse()
	root, err := os.Getwd()
	if err != nil {
		fail(err)
	}
	for _, input := range publicInputs {
		if _, err := os.Stat(filepath.Join(root, input)); err != nil {
			fail(fmt.Errorf("required public input %s: %w", input, err))
		}
	}
	generated, err := generate(root)
	if err != nil {
		fail(err)
	}
	stale := false
	for _, path := range outputFiles {
		content := generated[path]
		if *check {
			current, readErr := os.ReadFile(path)
			if readErr != nil || !bytes.Equal(current, content) {
				fmt.Fprintln(os.Stderr, "stale generated documentation:", path)
				stale = true
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			fail(err)
		}
		if err := os.WriteFile(path, content, 0o644); err != nil {
			fail(err)
		}
	}
	if stale {
		os.Exit(1)
	}
}

func generate(root string) (map[string][]byte, error) {
	cli, err := commandHelp(root, "--help")
	if err != nil {
		return nil, err
	}
	var out bytes.Buffer
	out.WriteString("---\ntitle: CLI reference\n---\n\nGenerated from `nomyr --help`; command presence does not imply later-phase product behavior.\n\n```text\n")
	out.WriteString(compactCommandHelp(string(cli)))
	out.WriteString("```\n\n")
	readme, err := readPublic(root, "cmd/nomyr/README.md")
	if err != nil {
		return nil, err
	}
	out.WriteString("See the [CLI behavior guide](cli-behavior.md) for supported output and scaffold details.\n\n")
	out.WriteString("## CLI behavior notes\n\n")
	out.WriteString(collapseBlankLines(strings.TrimPrefix(string(readme), "# CLI behavior\n\n")))
	for _, name := range []string{"version", "doctor", "login", "context", "demo", "telemetry", "scaffold"} {
		help, helpErr := commandHelp(root, name, "--help")
		if helpErr != nil {
			return nil, helpErr
		}
		fmt.Fprintf(&out, "\n## `%s`\n\n```text\n", name)
		out.WriteString(compactCommandHelp(string(help)))
		out.WriteString("```\n")
	}
	result := map[string][]byte{"docs-site/docs/reference/cli.md": out.Bytes()}

	api, err := readPublic(root, "api/openapi/v1.yaml")
	if err != nil {
		return nil, err
	}
	paths := regexp.MustCompile(`(?m)^  (/[^:]+):$`).FindAllSubmatch(api, -1)
	var apiDoc strings.Builder
	apiDoc.WriteString("---\ntitle: API contract\n---\n\nThis page summarizes the tracked OpenAPI contract. Contract declarations are not evidence of a running handler. The current local demo implements health and synthetic demo-estate routes; bearer authentication and `/capabilities` are not implemented by the scaffold.\n\n## Declared paths\n\n")
	for _, path := range paths {
		fmt.Fprintf(&apiDoc, "- `%s`\n", path[1])
	}
	result["docs-site/docs/reference/api.md"] = []byte(apiDoc.String())

	codeSource, err := readPublic(root, "internal/apperror/error.go")
	if err != nil {
		return nil, err
	}
	cliSource, err := readPublic(root, "cmd/nomyr/main.go")
	if err != nil {
		return nil, err
	}
	codePattern := regexp.MustCompile(`NHI-[A-Z]+-[0-9]{4}`)
	codes := map[string]bool{}
	for _, match := range append(codePattern.FindAll(codeSource, -1), codePattern.FindAll(cliSource, -1)...) {
		codes[string(match)] = true
	}
	codeList := make([]string, 0, len(codes))
	for code := range codes {
		codeList = append(codeList, code)
	}
	sort.Strings(codeList)
	var errorDoc strings.Builder
	errorDoc.WriteString("---\ntitle: Error codes\n---\n\nGenerated by scanning the explicit CLI and error-package source allowlist. The codes describe structured scaffold errors, not a complete product error catalogue.\n\n")
	for _, code := range codeList {
		fmt.Fprintf(&errorDoc, "- `%s`\n", code)
	}
	result["docs-site/docs/reference/errors.md"] = []byte(errorDoc.String())
	result["docs-site/docs/reference/configuration.md"] = []byte("---\ntitle: Configuration\n---\n\nNo general product configuration file, Helm values, or provider configuration is implemented in this Phase 0 scaffold. `NOMYR_CONFIG_HOME` is supported for local anonymous CLI usage-metrics configuration; it does not configure providers or product services.\n")

	capabilityBytes, err := readPublic(root, "schemas/capability-manifest.schema.json")
	if err != nil {
		return nil, err
	}
	eventBytes, err := readPublic(root, "schemas/event-envelope.schema.json")
	if err != nil {
		return nil, err
	}
	var capability, event map[string]any
	if err := json.Unmarshal(capabilityBytes, &capability); err != nil {
		return nil, err
	}
	if err := json.Unmarshal(eventBytes, &event); err != nil {
		return nil, err
	}
	result["docs-site/docs/reference/contracts.md"] = []byte(fmt.Sprintf("---\ntitle: Capability contract\n---\n\nThe tracked JSON Schema is `%s`. It defines a manifest shape; the presence of a schema does not establish an implemented provider or capability. No provider capability registry is implemented.\n", capability["$id"]))
	result["docs-site/docs/reference/capabilities.md"] = []byte(fmt.Sprintf("---\ntitle: Provider capabilities\n---\n\nThe tracked manifest schema is `%s`; a provider capability matrix or implemented provider registry does not exist in this scaffold.\n", capability["$id"]))
	result["docs-site/docs/reference/rules.md"] = []byte("---\ntitle: Rule catalog\n---\n\nNo executable rule catalog or rule engine is implemented. `nomyr scaffold rule new` creates a non-functional starter only.\n")
	result["docs-site/docs/reference/events.md"] = []byte(fmt.Sprintf("---\ntitle: Event contract\n---\n\nThe tracked JSON Schema is `%s`. Event production, delivery, retention, and a product event catalog are not implemented by this scaffold.\n", event["$id"]))

	catalogBytes, err := readPublic(root, "requirements/catalog.json")
	if err != nil {
		return nil, err
	}
	var catalog struct {
		Records []struct {
			ID     string `json:"id"`
			Kind   string `json:"kind"`
			Status string `json:"status"`
		} `json:"records"`
	}
	if err := json.Unmarshal(catalogBytes, &catalog); err != nil {
		return nil, err
	}
	counts := map[string]int{}
	for _, record := range catalog.Records {
		counts[record.Status]++
		if record.ID == "" || record.Kind == "" || record.Status == "" {
			return nil, fmt.Errorf("requirement record has empty metadata")
		}
	}
	var reqDoc strings.Builder
	reqDoc.WriteString("---\ntitle: Requirement status\n---\n\nGenerated from `requirements/catalog.json`. The register records status metadata, not proof of product functionality.\n\n| Status | Records |\n| --- | ---: |\n")
	statuses := make([]string, 0, len(counts))
	for status := range counts {
		statuses = append(statuses, status)
	}
	sort.Strings(statuses)
	for _, status := range statuses {
		fmt.Fprintf(&reqDoc, "| `%s` | %d |\n", status, counts[status])
	}
	fmt.Fprintf(&reqDoc, "\nTotal records: %d.\n", len(catalog.Records))
	result["docs-site/docs/reference/requirements.md"] = []byte(reqDoc.String())
	return result, nil
}

func collapseBlankLines(content string) string {
	return regexp.MustCompile(`(?:\n[ \t]*){3,}`).ReplaceAllString(content, "\n\n")
}

func compactCommandHelp(content string) string {
	return regexp.MustCompile(`\n[ \t]*\n`).ReplaceAllString(content, "\n")
}

func commandHelp(root string, args ...string) (output []byte, err error) {
	command := exec.Command(goExecutable(), append([]string{"run", "./cmd/nomyr"}, args...)...)
	command.Dir = root
	configHome, err := os.MkdirTemp("", "nomyr-docgen-config-")
	if err != nil {
		return nil, err
	}
	defer func() {
		if cleanupErr := os.RemoveAll(configHome); err == nil {
			err = cleanupErr
		}
	}()
	if err := os.WriteFile(filepath.Join(configHome, "telemetry.json"), []byte("{\"enabled\":false}\n"), 0o600); err != nil {
		return nil, err
	}
	command.Env = safeCommandEnvironment(os.Environ(), configHome)
	output, err = command.CombinedOutput()
	if err != nil {
		return nil, fmt.Errorf("nomyr %s help failed: %s", strings.Join(args, " "), strings.TrimSpace(string(output)))
	}
	return output, nil
}

func goExecutable() string {
	return filepath.Join(runtime.GOROOT(), "bin", "go")
}

func safeCommandEnvironment(environment []string, configHome string) []string {
	filtered := make([]string, 0, len(environment)+2)
	for _, variable := range environment {
		if !strings.HasPrefix(variable, "PATH=") && !strings.HasPrefix(variable, "NOMYR_CONFIG_HOME=") {
			filtered = append(filtered, variable)
		}
	}
	return append(filtered, "PATH=/usr/bin:/bin", "NOMYR_CONFIG_HOME="+configHome)
}

func readPublic(root, path string) ([]byte, error) {
	for _, allowed := range publicInputs {
		if path == allowed {
			return os.ReadFile(filepath.Join(root, allowed))
		}
	}
	return nil, fmt.Errorf("source is not on the public documentation allowlist: %s", path)
}

func fail(err error) { fmt.Fprintln(os.Stderr, err); os.Exit(1) }
